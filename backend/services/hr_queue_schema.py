"""HR/IT escalation queue, audit trail and shared login rate limiting (migration 008).

Single source of truth:
  * `POSTGRES_DDL` is executed by backend/migrations/008_hr_escalation_queue.py on existing databases and is
    shipped verbatim as docker/postgres/05_hr_queue.sql for fresh Docker databases (a test keeps them identical).
  * `SQLITE_DDL` (tables and indexes only) is applied by db.init_db for the SQLite test/legacy backend.

Every statement is idempotent and additive: the role CHECK constraints are replaced by wider ones (adding the
`hr` role for HR/IT support staff, who are not linked to an employee), three nullable columns are added to
escalations, and two tables are created. No row is changed or deleted.
"""
from typing import Dict, List

ESCALATION_TRANSITIONS: Dict[str, tuple] = {
    "open": ("in_progress", "resolved"),
    "in_progress": ("open", "resolved"),
    "resolved": ("in_progress", "closed"),
    "closed": (),
}
EVENT_ACTIONS = ("created", "viewed", "status_changed")
NOTE_MAX_LENGTH = 1000

POSTGRES_DDL = """\
-- OnboardAI migration 008: HR/IT escalation queue, audit trail, shared login rate limiting (PostgreSQL 16).
-- Idempotent and additive: widens two CHECK constraints, adds nullable columns and new tables; no row is changed.
ALTER TABLE public.user_accounts DROP CONSTRAINT IF EXISTS user_accounts_role_check;
ALTER TABLE public.user_accounts ADD CONSTRAINT user_accounts_role_check CHECK (role IN ('employee', 'admin', 'hr'));
ALTER TABLE public.user_accounts DROP CONSTRAINT IF EXISTS user_accounts_employee_required;
ALTER TABLE public.user_accounts ADD CONSTRAINT user_accounts_employee_required
    CHECK (role IN ('admin', 'hr') OR employee_id IS NOT NULL);
ALTER TABLE public.escalations ADD COLUMN IF NOT EXISTS updated_at text;
ALTER TABLE public.escalations ADD COLUMN IF NOT EXISTS resolution_note text;
ALTER TABLE public.escalations ADD COLUMN IF NOT EXISTS handled_by integer REFERENCES public.user_accounts(id);
CREATE INDEX IF NOT EXISTS idx_escalations_status ON public.escalations (status);
CREATE TABLE IF NOT EXISTS public.escalation_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escalation_id integer NOT NULL REFERENCES public.escalations(id) ON DELETE CASCADE,
    actor_user_id integer REFERENCES public.user_accounts(id),
    action text NOT NULL CHECK (action IN ('created', 'viewed', 'status_changed')),
    from_status text,
    to_status text,
    note text CHECK (note IS NULL OR length(note) <= 1000),
    created_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_escalation_events_escalation_id ON public.escalation_events (escalation_id);
CREATE TABLE IF NOT EXISTS public.login_failures (
    key_hash text NOT NULL,
    failed_at double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_login_failures_key ON public.login_failures (key_hash, failed_at);
CREATE INDEX IF NOT EXISTS idx_login_failures_failed_at ON public.login_failures (failed_at);
"""

NEW_TABLES = ("escalation_events", "login_failures")
ESCALATION_COLUMNS = (("updated_at", "text"), ("resolution_note", "text"),
                      ("handled_by", "integer REFERENCES user_accounts(id)"))


def _sqlite_statements() -> List[str]:
    keep = [s.strip() for s in POSTGRES_DDL.split(";") if s.strip().startswith(("CREATE TABLE", "CREATE INDEX"))]
    sqlite = []
    for statement in keep:
        statement = (statement.replace("public.", "")
                     .replace("id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "id INTEGER PRIMARY KEY AUTOINCREMENT")
                     .replace("double precision", "REAL"))
        sqlite.append(statement + ";")
    return sqlite


SQLITE_DDL = "\n".join(_sqlite_statements())

# Read-only presence checks (db.init_db refuses to start without them; migration 008 --verify reports them).
VERIFY_QUERIES = {
    "escalation_events table": "SELECT to_regclass('public.escalation_events') IS NOT NULL AS ok",
    "login_failures table": "SELECT to_regclass('public.login_failures') IS NOT NULL AS ok",
    "escalations.handled_by column": """SELECT EXISTS (SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'escalations' AND column_name = 'handled_by') AS ok""",
    "hr role allowed on user_accounts": """SELECT EXISTS (SELECT 1 FROM pg_constraint c JOIN pg_namespace n
        ON n.oid = c.connamespace WHERE n.nspname = 'public' AND c.conname = 'user_accounts_role_check'
        AND pg_get_constraintdef(c.oid) LIKE '%''hr''%') AS ok""",
}


def _statements() -> List[str]:
    """The DDL as individual statements (comment lines removed)."""
    # Remove comment lines first: comments may contain ';'.
    code = "\n".join(line for line in POSTGRES_DDL.splitlines() if not line.lstrip().startswith("--"))
    return [chunk.strip() for chunk in code.split(";") if chunk.strip()]


def build_ddl_plan():
    """Migration 008 DDL as a db_roles.Plan (executed by the table owner)."""
    from psycopg2 import sql

    from backend.services.db_roles import Plan

    plan = Plan()
    for statement in _statements():
        plan.add(statement.splitlines()[0][:100], sql.SQL(statement))
    return plan


def build_grant_plan(conn, app_role: str):
    """APP-role grants on the objects of migration 008 (run after the DDL; empty if the role does not exist)."""
    from backend.services import db_roles

    db_roles.validate_role_names(app_role, db_roles.READER_ROLE)
    plan = db_roles.Plan()
    if db_roles._role(conn, app_role) is None:
        plan.notes.append(f"Role {app_role} does not exist: no grants (run migration 005 afterwards).")
        return plan
    db_roles.plan_app_grants(plan, conn, app_role, ("escalations",) + NEW_TABLES)
    return plan


def privilege_problems(conn, app_role: str) -> List[str]:
    """Expected APP-role privileges on the 008 objects (only if the role exists)."""
    from backend.services import db_roles

    if db_roles._role(conn, app_role) is None:
        return []
    problems = []
    with conn.cursor() as cur:
        for table in ("escalations",) + NEW_TABLES:
            for privilege, columns in db_roles.APP_PRIVILEGES[table]:
                for column in columns or (None,):
                    if column:
                        cur.execute("SELECT has_column_privilege(%s, %s, %s, %s) AS ok",
                                    (app_role, f"public.{table}", column, privilege))
                    else:
                        cur.execute("SELECT has_table_privilege(%s, %s, %s) AS ok",
                                    (app_role, f"public.{table}", privilege))
                    row = cur.fetchone()
                    if not (row["ok"] if isinstance(row, dict) else row[0]):
                        problems.append(f"{app_role} lacks {privilege}{'(' + column + ')' if column else ''} on {table}")
            for privilege in ("TRUNCATE",) + (("DELETE",) if table not in db_roles.APP_DELETE_TABLES else ()):
                cur.execute("SELECT has_table_privilege(%s, %s, %s) AS ok", (app_role, f"public.{table}", privilege))
                row = cur.fetchone()
                if row["ok"] if isinstance(row, dict) else row[0]:
                    problems.append(f"{app_role} must not have {privilege} on {table}")
    return problems


def missing_objects(conn) -> List[str]:
    """Names of migration-008 objects that are absent (PostgreSQL; empty list = migration applied)."""
    missing = []
    with conn.cursor() as cur:
        for label, query in VERIFY_QUERIES.items():
            cur.execute(query)
            row = cur.fetchone()
            value = row["ok"] if isinstance(row, dict) else row[0]
            if not value:
                missing.append(label)
    return missing
