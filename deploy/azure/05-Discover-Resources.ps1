<#
.SYNOPSIS
  Step 0.5 - discover the EXISTING Azure resources (read-only) and write deploy/azure/config.psd1 (git-ignored).
.DESCRIPTION
  Finds, by name, the backend Web App (and from it the resource group, region and App Service plan), the frontend
  Web App if it exists, the container registry (its real login server - a TenantReuse/DNL-scoped registry has a
  hashed host name), and a PostgreSQL flexible server (its real FQDN). Nothing is created or changed in Azure.
  Values that cannot be found are written as <placeholders>, which -Execute in later steps refuses.
.EXAMPLE
  az login; .\05-Discover-Resources.ps1 -BackendApp onboardai-eliksha-backend -AcrName onboardaielikshaacr
#>
param(
    [string] $BackendApp = 'onboardai-eliksha-backend',
    [string] $FrontendApp = 'onboardai-eliksha-frontend',
    [string] $AcrName = 'onboardaielikshaacr',
    [string] $PgServer = '',
    # Local path of the external secrets file: set ONBOARDAI_SECRETS_FILE or pass -SecretsFile (never committed).
    [string] $SecretsFile = $(if ($env:ONBOARDAI_SECRETS_FILE) { $env:ONBOARDAI_SECRETS_FILE } else { '<path-to-secrets-file>' }),
    [string] $OutFile = (Join-Path $PSScriptRoot 'config.psd1')
)
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'OnboardAI.Azure.psm1') -Force
$null = Initialize-Deployment -ConfigPath (Join-Path $PSScriptRoot 'config.example.psd1') -Execute -AllowPlaceholders   # read-only queries below

function Get-Json([string[]] $Arguments) { return Find-AzResource -Arguments $Arguments }
function Get-Value($value, [string] $placeholder) { if ($value) { return [string]$value } return "<$placeholder>" }

$account = Get-Json @('account', 'show')
if (-not $account) { throw "Not signed in to Azure CLI. Run 'az login' first." }
Write-Host "Subscription: $($account.name)"

$backend = Get-Json @('webapp', 'list', '--query', "[?name=='$BackendApp'] | [0]")
if (-not $backend) { throw "Backend Web App '$BackendApp' not found in subscription $($account.name)." }
$rg = $backend.resourceGroup
$planId = $backend.appServicePlanId
if (-not $planId) { $planId = $backend.serverFarmId }
$plan = Get-Json @('appservice', 'plan', 'show', '--ids', $planId)
$frontend = Get-Json @('webapp', 'list', '--query', "[?name=='$FrontendApp'] | [0]")
$acr = Get-Json @('acr', 'list', '--query', "[?name=='$AcrName'] | [0]")
$pgQuery = if ($PgServer) { "[?name=='$PgServer'] | [0]" } else { "[?resourceGroup=='$rg'] | [0]" }
$pg = Get-Json @('postgres', 'flexible-server', 'list', '--query', $pgQuery)
$tag = (& git -C (Get-RepositoryRoot) rev-parse --short HEAD 2>$null)
if ($tag) { $tag = "$tag-$(Get-Date -Format 'yyyyMMddHHmm')" }

$values = [ordered]@{
    SubscriptionId = $account.id
    ResourceGroup  = $rg
    Location       = ($backend.location -replace '\s', '').ToLower()
    Prefix         = 'onboardai-eliksha'
    PlanName       = Get-Value $plan.name 'plan-name'
    PlanSku        = Get-Value $plan.sku.name 'plan-sku'
    BackendApp     = $BackendApp
    FrontendApp    = $FrontendApp
    FrontendExists = [bool]$frontend
    AcrName        = Get-Value $acr.name 'acr-name'
    AcrLoginServer = Get-Value $acr.loginServer 'acr-login-server'
    ImageTag       = Get-Value $tag 'image-tag'
    PgServer       = Get-Value $pg.name 'postgres-server-name'
    PgHost         = Get-Value $pg.fullyQualifiedDomainName 'postgres-fqdn'
    PgDatabase     = 'onboardai'
    PgAdminUser    = Get-Value $pg.administratorLogin 'postgres-admin-user'
    PgSkuName      = 'Standard_B1ms'
    PgTier         = 'Burstable'
    PgStorageGb    = 32
    PgVersion      = '16'
    SecretsFile    = $SecretsFile
    TrustedProxyHops = 3
}
$header = '# GENERATED by 05-Discover-Resources.ps1 on ' + (Get-Date -Format 's') + ' - git-ignored; re-run to refresh.'
$lines = @($header, '@{')   # (separate variable: in an array literal ',' binds tighter than '+')
foreach ($k in $values.Keys) {
    $v = $values[$k]
    if ($v -is [bool]) { $lines += "    $k = `$$($v.ToString().ToLower())" }
    elseif ($v -is [int]) { $lines += "    $k = $v" }
    else { $lines += "    $k = '" + ([string]$v).Replace("'", "''") + "'" }
}
$lines += "    Tags = @{ project = 'onboardai'; owner = 'eliksha'; environment = 'capstone' }"
$lines += '}'
[System.IO.File]::WriteAllText($OutFile, ($lines -join "`r`n") + "`r`n", (New-Object System.Text.UTF8Encoding($false)))

Write-Host "`nDiscovered:" -ForegroundColor Cyan
foreach ($k in 'ResourceGroup', 'Location', 'PlanName', 'PlanSku', 'BackendApp', 'FrontendExists', 'AcrLoginServer', 'PgServer', 'PgHost', 'PgAdminUser', 'ImageTag') {
    Write-Host ("  {0,-15} {1}" -f $k, $values[$k])
}
Write-Host "Written: $OutFile (git-ignored)" -ForegroundColor Green
if (($values.Values | Where-Object { "$_" -match '^<' }).Count -gt 0) {
    Write-Warning 'Some resources were not found (shown as <...>): create them or pass -PgServer / names, then re-run.'
}
