-- OnboardAI migration 008: HR/IT escalation queue, audit trail, shared login rate limiting (PostgreSQL 16).
-- Idempotent and additive: widens two CHECK constraints, adds nullable columns and new tables; no row is changed.
ALTER TABLE public.user_accounts DROP CONSTRAINT IF EXISTS user_accounts_role_check;
ALTER TABLE public.user_accounts ADD CONSTRAINT user_accounts_role_check CHECK (role IN ('employee', 'admin', 'hr'));
ALTER TABLE public.user_accounts DROP CONSTRAINT IF EXISTS user_accounts_employee_required;
ALTER TABLE public.user_accounts ADD CONSTRAINT user_accounts_employee_required
    CHECK (role IN ('admin', 'hr') OR employee_id IS NOT NULL);
ALTER TABLE public.escalations ADD COLUMN IF NOT EXISTS updated_at text;
ALTER TABLE public.escalations ADD COLUMN IF NOT EXISTS resolution_note text;
ALTER TABLE public.escalations ADD COLUMN IF NOT EXISTS handled_by integer REFERENCES public.user_accounts(id);
CREATE INDEX IF NOT EXISTS idx_escalations_status ON public.escalations (status);
CREATE TABLE IF NOT EXISTS public.escalation_events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escalation_id integer NOT NULL REFERENCES public.escalations(id) ON DELETE CASCADE,
    actor_user_id integer REFERENCES public.user_accounts(id),
    action text NOT NULL CHECK (action IN ('created', 'viewed', 'status_changed')),
    from_status text,
    to_status text,
    note text CHECK (note IS NULL OR length(note) <= 1000),
    created_at text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_escalation_events_escalation_id ON public.escalation_events (escalation_id);
CREATE TABLE IF NOT EXISTS public.login_failures (
    key_hash text NOT NULL,
    failed_at double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_login_failures_key ON public.login_failures (key_hash, failed_at);
CREATE INDEX IF NOT EXISTS idx_login_failures_failed_at ON public.login_failures (failed_at);
