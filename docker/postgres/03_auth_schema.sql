-- OnboardAI authentication tables (PostgreSQL 16). Idempotent; adds tables only.
-- No accounts are created here: provision them with `python -m backend.manage_accounts`.
CREATE TABLE IF NOT EXISTS public.user_accounts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    employee_id text UNIQUE REFERENCES public.employees(employee_id),
    role text NOT NULL DEFAULT 'employee' CHECK (role IN ('employee', 'admin')),
    is_active integer NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at bigint NOT NULL,
    updated_at bigint NOT NULL,
    CONSTRAINT user_accounts_employee_required CHECK (role = 'admin' OR employee_id IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS public.user_sessions (
    token_hash text PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.user_accounts(id) ON DELETE CASCADE,
    csrf_token text NOT NULL,
    created_at bigint NOT NULL,
    last_seen_at bigint NOT NULL,
    expires_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_sessions_user_id ON public.user_sessions (user_id);
